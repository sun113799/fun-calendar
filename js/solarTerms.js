/**
 * 查询某一天是否是节气
 * @param {number} year - 公历年
 * @param {number} month - 公历月（1-12）
 * @param {number} day - 公历日
 * @returns {{ name: string, termIndex: number } | null}
 */
function getSolarTerm(year, month, day) {
  const yearIndex = year - 2020;
  if (yearIndex < 0 || yearIndex >= SOLAR_TERM_DATES.length) return null;

  const dates = SOLAR_TERM_DATES[yearIndex];

  // 节气的分布：index 0,1 → 1月，2,3 → 2月，...，22,23 → 12月
  // 但有例外：小寒(index 0)偶尔在 12 月
  for (let i = 0; i < 24; i++) {
    const termMonth = Math.floor(i / 2) + 1;
    if (termMonth === month && dates[i] === day) {
      return { name: SOLAR_TERMS[i], termIndex: i };
    }
  }

  // 处理小寒在 12 月的特殊情况（index 0 可能在 12 月）
  if (month === 12 && dates[0] >= 29) {
    // 小寒在 12 月底
    return { name: SOLAR_TERMS[0], termIndex: 0 };
  }

  return null;
}
